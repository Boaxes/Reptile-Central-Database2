        WHEN 'Employee' THEN
            UPDATE Employees
            SET firstName = p1,
                lastName  = p2,
                jobTitle  = p3
            WHERE employeeID = CAST(target_id AS UNSIGNED INTEGER);

        WHEN 'Product Type' THEN
            UPDATE ProductTypes
            SET productTypeName = p1
            WHERE productTypeCode = target_id;

        WHEN 'Animal' THEN
            UPDATE Animals
            SET age         = CAST(p1 AS UNSIGNED INTEGER),
                price       = CAST(p2 AS DECIMAL(10,2)),
                isAvailable = CASE WHEN p3 = 'Yes' THEN 1 ELSE 0 END
            WHERE animalID = CAST(target_id AS UNSIGNED INTEGER);

        WHEN 'Product' THEN
            UPDATE Products
            SET productName     = p1,
                productTypeCode = p2,
                price           = CAST(p3 AS DECIMAL(10,2)),
                stock           = CAST(p4 AS UNSIGNED INTEGER)
            WHERE productID = CAST(target_id AS UNSIGNED INTEGER);

        WHEN 'Employee Assignment' THEN
            UPDATE EmployeeAnimals
            SET animalID   = CAST(p1 AS UNSIGNED INTEGER),
                employeeID = CAST(p2 AS UNSIGNED INTEGER)
            WHERE animalDetailsID = CAST(target_id AS UNSIGNED INTEGER);

        -- Upserts the order detail row then recalculates the order total.
        WHEN 'Order Detail' THEN
            IF EXISTS (
                SELECT 1
                FROM OrderDetails
                WHERE orderID   = CAST(target_id AS UNSIGNED INTEGER)
                  AND productID = CAST(p1 AS UNSIGNED INTEGER)
            ) THEN
                UPDATE OrderDetails
                SET quantity  = CAST(p2 AS UNSIGNED INTEGER),
                    unitPrice = (SELECT price FROM Products WHERE productID = CAST(p1 AS UNSIGNED INTEGER))
                WHERE orderID   = CAST(target_id AS UNSIGNED INTEGER)
                  AND productID = CAST(p1 AS UNSIGNED INTEGER);
            ELSE
                INSERT INTO OrderDetails (orderID, productID, quantity, unitPrice)
                VALUES (
                    CAST(target_id AS UNSIGNED INTEGER),
                    CAST(p1 AS UNSIGNED INTEGER),
                    CAST(p2 AS UNSIGNED INTEGER),
                    (SELECT price FROM Products WHERE productID = CAST(p1 AS UNSIGNED INTEGER))
                );
            END IF;

            UPDATE Orders
            SET orderTotal = (
                SELECT COALESCE(SUM(quantity * unitPrice), 0.00)
                FROM OrderDetails
                WHERE orderID = CAST(target_id AS UNSIGNED INTEGER)
            )
            WHERE orderID = CAST(target_id AS UNSIGNED INTEGER);

        ELSE
            SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Unsupported update_id passed to sp_generic_update.';

    END CASE;
END //
